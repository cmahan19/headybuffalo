const GENERATOR = "scripts/generate-art.mjs (seeded procedural SVG → sharp raster)";
const today = new Date().toISOString().slice(0, 10);
const manifest = [];
const f = (n) => n.toFixed(1);

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Shared filters: topographic warp, paper grain, soft blur for shadows/glows. */
function defs({ w, seed, warp = 0.06, freq = 0.0035, grain = 0.06 }) {
  return `
  <filter id="topo" x="-20%" y="-20%" width="140%" height="140%">
    <feTurbulence type="fractalNoise" baseFrequency="${freq * (2400 / w)}" numOctaves="2" seed="${seed}" result="n"/>
    <feDisplacementMap in="SourceGraphic" in2="n" scale="${f(w * warp)}" xChannelSelector="R" yChannelSelector="G"/>
  </filter>
  <filter id="grain" x="0" y="0" width="100%" height="100%">
    <feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="2" seed="${seed + 7}"/>
    <feColorMatrix type="saturate" values="0"/>
    <feComponentTransfer><feFuncA type="table" tableValues="0 ${grain}"/></feComponentTransfer>
  </filter>
  <filter id="soft" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="${f(w * 0.012)}"/></filter>`;
}

/** Topographic contour lines: concentric rings warped by noise. */
function contours({ cx, cy, count, step, stroke, opacity = 0.5, width = 1.5, ratio = 0.7 }) {
  let out = "";
  for (let i = 1; i <= count; i++) {
    const r = i * step;
    out += `<ellipse cx="${f(cx)}" cy="${f(cy)}" rx="${f(r)}" ry="${f(r * ratio)}" fill="none" stroke="${stroke}" stroke-opacity="${(opacity * (1 - i / (count * 1.4))).toFixed(3)}" stroke-width="${width}"/>`;
  }
  return `<g filter="url(#topo)">${out}</g>`;
}

/** Paper-cut hill silhouette across the full width. */
function hill({ w, h, base, amp, seed, fill, opacity = 1, shadow = true }) {
  const r = rng(seed);
  const waves = [0, 1, 2].map(() => ({ k: (0.6 + r() * 2.2) * (Math.PI * 2) / w, p: r() * 10, a: amp * (0.35 + r() * 0.65) }));
  const pts = [];
  for (let x = -20; x <= w + 20; x += w / 120) {
    const y = base - waves.reduce((s, wv) => s + wv.a * Math.sin(wv.k * x + wv.p), 0);
    pts.push(`${f(x)},${f(y)}`);
  }
  const d = `M-20,${h + 20} L${pts.join(" L")} L${w + 20},${h + 20} Z`;
  const sh = shadow ? `<path d="${d}" transform="translate(0,-6)" fill="#000" fill-opacity="0.12" filter="url(#soft)"/>` : "";
  return `${sh}<path d="${d}" fill="${fill}" fill-opacity="${opacity}"/>`;
}

const glow = (cx, cy, r, color, op = 0.55) =>
  `<radialGradient id="g${f(cx)}${f(cy)}"><stop offset="0" stop-color="${color}" stop-opacity="${op}"/><stop offset="1" stop-color="${color}" stop-opacity="0"/></radialGradient><circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}" fill="url(#g${f(cx)}${f(cy)})"/>`;

const grainLayer = (w, h) => `<rect width="${w}" height="${h}" filter="url(#grain)"/>`;
const svgDoc = (w, h, body, d) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><defs>${defs({ w, ...d })}</defs>${body}</svg>`;

async function asset(entry, svg, { format = "webp", quality = 80 } = {}) {
  const out = join(outDir, entry.file);
  let img = sharp(Buffer.from(svg), { density: 72 });
  img = format === "jpeg" ? img.jpeg({ quality, mozjpeg: true }) : img.webp({ quality, effort: 6 });
  const { size } = await img.toFile(out);
  manifest.push({
    id: entry.id, file: `/art/generated/${entry.file}`, kind: entry.kind, purpose: entry.purpose, routes: entry.routes,
    width: entry.w, height: entry.h, bytes: size, date: today, source: "generated", generator: GENERATOR, seed: entry.seed,
    palette: entry.palette, decorative_only: true, product_proof: false, alt: "", approval_status: "provisional",
  });
  console.log(`${entry.file.padEnd(36)} ${entry.w}x${entry.h}  ${(size / 1024).toFixed(0)} KB`);
}


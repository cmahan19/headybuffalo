// Procedural decorative art generator for Heady Buffalo.
//
// Style: black chrome + natural (topographic contour lines, paper-cut hills, studio stages with soft
// dappled leaf shadows) with color as accents. Every output is decorative only: no text, logos, people,
// products, labels, or claim symbols. Metadata for each file is written to src/lib/art-manifest.json
// (see docs/IMAGE_GENERATION_AND_ASSET_POLICY.md).
//
// Usage: node scripts/generate-art.mjs   (deterministic: same seeds → same images; cleans its own output dir)


// 4. Concept stages 4:5 ×20: studio backdrop, soft dappled leaf shadows, empty stone pedestal.
//    Alternates light (bone/sand) and dark (chrome) stages; one accent glow per concept. No product shown.
const accents = [C.teal, C.ochre, C.cobalt, C.clay, C.sage, C.berry, C.aqua, C.olive, C.coral, C.yellow];
function leafShadows(w, h, seed, color, op) {
  const r = rng(seed);
  let out = "";
  for (let i = 0; i < 9; i++) {
    const x = r() * w, y = r() * h * 0.6, len = 120 + r() * 160, wid = len * (0.28 + r() * 0.12), rot = r() * 180;
    out += `<path d="M0,0 C${f(wid)},${f(-len * 0.3)} ${f(wid)},${f(-len * 0.75)} 0,${f(-len)} C${f(-wid)},${f(-len * 0.75)} ${f(-wid)},${f(-len * 0.3)} 0,0Z" transform="translate(${f(x)} ${f(y)}) rotate(${f(rot)})" fill="${color}" fill-opacity="${op}"/>`;
    out += `<path d="M0,0 L0,${f(-len)}" transform="translate(${f(x)} ${f(y)}) rotate(${f(rot)})" stroke="${color}" stroke-opacity="${op * 0.7}" stroke-width="5"/>`;
  }
  return `<g filter="url(#soft)">${out}</g>`;
}

// Internal product concepts: ideas to validate, NOT products. None has a price, stock, or cart path,
// and none may appear in Product schema, the sitemap, search results, or "featured products".
// Public surfaces (/ideas, homepage module) show only `publicName`, `publicDescription`, and the concept
// visual, always with the "Concept Only / Not available for purchase" labels, and are noindexed.
//
// Concepts 1-10 are general product ideas; 11-30 are hand-made DIY products the owner can build, each with an
// internal build guide (21-30 are the easiest: beginner skill, cheap, light to ship). The count is enforced by tests/unit/concepts-and-claims.spec.ts.

import type { ColorFamilyKey } from "./colorMap";
import type { ProductStatus } from "./readiness";

export type ConceptCategoryKey = "craft" | "home" | "gifts" | "carry";

